-- ENGANO web app data: accounts, workspaces, the review pipeline, revision history and comments.
--
-- Names are unqualified on purpose so the same file can be applied into a scratch schema in tests.
-- Every table has row level security ON with no policies: the browser and the public API keys can
-- never read these tables. Only the ENGANO backend, which connects with the database URL, can.

BEGIN;

CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS accounts (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  purpose TEXT NOT NULL,
  brand TEXT,
  salt TEXT NOT NULL,
  hash TEXT NOT NULL,
  created_by TEXT,
  created_at DOUBLE PRECISION NOT NULL,
  whatsapp TEXT,
  discord_id TEXT,
  supabase_id TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS accounts_email ON accounts (lower(email));
CREATE UNIQUE INDEX IF NOT EXISTS accounts_brand ON accounts (lower(brand)) WHERE brand IS NOT NULL;

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  expires_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS workspaces (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  code TEXT NOT NULL UNIQUE,
  created_by TEXT NOT NULL REFERENCES accounts(id),
  created_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('Creator', 'Reviewer')),
  UNIQUE (workspace_id, user_id)
);

CREATE TABLE IF NOT EXISTS requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  UNIQUE (user_id)
);

CREATE TABLE IF NOT EXISTS assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  due_date TEXT NOT NULL,
  created_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS guidelines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('DO', 'DON''T')),
  text TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  creator_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  findings TEXT NOT NULL,
  status TEXT NOT NULL,
  approved_by TEXT,
  reviewer_comment TEXT,
  ai_status TEXT,
  created_at DOUBLE PRECISION NOT NULL,
  updated_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS reviewer_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id BIGINT NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
  workspace_id BIGINT NOT NULL,
  reviewer_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  action TEXT NOT NULL,
  created_at DOUBLE PRECISION NOT NULL
);

-- Revision history: one row per version the creator sent. The submission row holds the latest.
CREATE TABLE IF NOT EXISTS submission_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id BIGINT NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
  version INTEGER NOT NULL,
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  findings TEXT NOT NULL,
  ai_status TEXT,
  author_id TEXT NOT NULL,
  created_at DOUBLE PRECISION NOT NULL,
  UNIQUE (submission_id, version)
);

-- The timeline of one submission: sent, cleared, approved, rejected, resubmitted, and comments.
CREATE TABLE IF NOT EXISTS submission_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id BIGINT NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  actor_id TEXT,
  version INTEGER NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  created_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS submission_events_submission ON submission_events (submission_id, id);

ALTER TABLE meta ENABLE ROW LEVEL SECURITY;
ALTER TABLE accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE workspaces ENABLE ROW LEVEL SECURITY;
ALTER TABLE members ENABLE ROW LEVEL SECURITY;
ALTER TABLE requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE guidelines ENABLE ROW LEVEL SECURITY;
ALTER TABLE submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviewer_actions ENABLE ROW LEVEL SECURITY;
ALTER TABLE submission_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE submission_events ENABLE ROW LEVEL SECURITY;

-- Everything one person may see, in a single call (the database is far from the backend, so the
-- app asks once instead of fifteen times). Mirrors TeamStore.snapshot for SQLite.
CREATE OR REPLACE FUNCTION engano_snapshot(p_account TEXT) RETURNS JSONB
LANGUAGE plpgsql STABLE AS $fn$
DECLARE
  me RECORD;
  v_purpose TEXT;
  ws BIGINT[];
BEGIN
  SELECT id, name, email, accounts.purpose AS purpose, brand, whatsapp, discord_id INTO me FROM accounts WHERE accounts.id = p_account;
  IF NOT FOUND THEN RETURN NULL; END IF;
  v_purpose := me.purpose;

  IF v_purpose = 'Business' THEN
    SELECT COALESCE(array_agg(w.id ORDER BY w.id DESC), '{}') INTO ws FROM workspaces w WHERE w.created_by = p_account;
  ELSE
    SELECT COALESCE(array_agg(w.id ORDER BY m.id), '{}') INTO ws FROM workspaces w JOIN members m ON m.workspace_id = w.id WHERE m.user_id = p_account;
  END IF;

  RETURN jsonb_build_object(
    'me', jsonb_build_object('id', me.id, 'name', me.name, 'email', me.email, 'purpose', me.purpose, 'brand', me.brand,
                             'whatsapp', COALESCE(me.whatsapp, ''), 'discordId', COALESCE(me.discord_id, '')),

    'workspaces', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', w.id, 'name', w.name,
        'code', CASE WHEN v_purpose = 'Business' THEN w.code ELSE '' END,
        't', w.created_at, 'createdBy', w.created_by,
        'members', COALESCE((SELECT jsonb_agg(jsonb_build_object('id', m.id, 'userId', m.user_id, 'role', m.role) ORDER BY m.id)
                             FROM members m WHERE m.workspace_id = w.id AND (v_purpose <> 'Content Creator' OR m.user_id = p_account)), '[]'::jsonb),
        'requests', CASE WHEN v_purpose = 'Business'
                         THEN COALESCE((SELECT jsonb_agg(jsonb_build_object('id', r.id, 'userId', r.user_id) ORDER BY r.id)
                                        FROM requests r WHERE r.workspace_id = w.id), '[]'::jsonb)
                         ELSE '[]'::jsonb END
      ) ORDER BY u.ord)
      FROM unnest(ws) WITH ORDINALITY u(id, ord) JOIN workspaces w ON w.id = u.id), '[]'::jsonb),

    'assignments', COALESCE((
      SELECT jsonb_agg(jsonb_build_object('id', a.id, 'workspaceId', a.workspace_id, 'title', a.title, 'description', a.description,
                                          'dueDate', a.due_date, 't', a.created_at) ORDER BY a.id DESC)
      FROM assignments a WHERE a.workspace_id = ANY(ws)), '[]'::jsonb),

    'guidelines', COALESCE((
      SELECT jsonb_object_agg(u.id::text, COALESCE((SELECT jsonb_agg(jsonb_build_object('id', g.id, 'type', g.kind, 'text', g.text) ORDER BY g.id)
                                                    FROM guidelines g WHERE g.workspace_id = u.id), '[]'::jsonb))
      FROM unnest(ws) u(id)), '{}'::jsonb),

    'submissions', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', s.id, 'title', s.title, 'content', s.content, 'findings', s.findings::jsonb, 'status', s.status,
        'reviewerComment', s.reviewer_comment, 'workspaceId', s.workspace_id, 'creatorId', s.creator_id,
        'approvedBy', s.approved_by, 'aiStatus', s.ai_status, 'at', floor(s.created_at * 1000)::bigint,
        'version', COALESCE((SELECT max(v.version) FROM submission_versions v WHERE v.submission_id = s.id), 1),
        'comments', (SELECT count(*) FROM submission_events e WHERE e.submission_id = s.id AND e.kind = 'comment')
      ) ORDER BY s.id DESC)
      FROM submissions s
      WHERE (v_purpose = 'Content Creator' AND s.creator_id = p_account) OR (v_purpose <> 'Content Creator' AND s.workspace_id = ANY(ws))), '[]'::jsonb),

    'reviewerActions', CASE WHEN v_purpose = 'Content Creator' THEN '[]'::jsonb ELSE COALESCE((
      SELECT jsonb_agg(jsonb_build_object('id', a.id, 'submissionId', a.submission_id, 'workspaceId', a.workspace_id, 'title', a.title,
                                          'action', a.action, 'createdAt', '', 'reviewerId', a.reviewer_id, 'at', floor(a.created_at * 1000)::bigint) ORDER BY a.id DESC)
      FROM reviewer_actions a WHERE a.workspace_id = ANY(ws) AND (v_purpose <> 'Reviewer' OR a.reviewer_id = p_account)), '[]'::jsonb) END,

    'people', COALESCE((
      SELECT jsonb_object_agg(a.id, a.name) FROM accounts a WHERE a.id IN (
        SELECT user_id FROM members WHERE workspace_id = ANY(ws)
        UNION SELECT creator_id FROM submissions
              WHERE (v_purpose = 'Content Creator' AND creator_id = p_account) OR (v_purpose <> 'Content Creator' AND workspace_id = ANY(ws))
        UNION SELECT reviewer_id FROM reviewer_actions
              WHERE v_purpose <> 'Content Creator' AND workspace_id = ANY(ws) AND (v_purpose <> 'Reviewer' OR reviewer_id = p_account)
        UNION SELECT user_id FROM requests WHERE v_purpose = 'Business' AND workspace_id = ANY(ws)
        UNION SELECT created_by FROM workspaces WHERE id = ANY(ws)
        UNION SELECT p_account)), '{}'::jsonb),

    'directory', CASE WHEN v_purpose = 'Content Creator' THEN COALESCE((
      SELECT jsonb_agg(jsonb_build_object('managerId', a.id, 'managerName', a.name, 'brand', a.brand,
        'workspaces', COALESCE((SELECT jsonb_agg(jsonb_build_object('id', w.id, 'name', w.name) ORDER BY w.id) FROM workspaces w WHERE w.created_by = a.id), '[]'::jsonb))
        ORDER BY lower(a.brand))
      FROM accounts a WHERE a.purpose = 'Business'), '[]'::jsonb) ELSE '[]'::jsonb END,

    'pendingRequest', CASE WHEN v_purpose = 'Content Creator' THEN
      (SELECT jsonb_build_object('id', w.id, 'name', w.name) FROM requests r JOIN workspaces w ON w.id = r.workspace_id WHERE r.user_id = p_account)
      ELSE NULL END,

    'myReviewers', CASE WHEN v_purpose = 'Business' THEN COALESCE((
      SELECT jsonb_agg(jsonb_build_object('id', a.id, 'name', a.name, 'email', a.email) ORDER BY a.name)
      FROM accounts a WHERE a.purpose = 'Reviewer' AND a.created_by = p_account), '[]'::jsonb) ELSE '[]'::jsonb END
  );
END
$fn$;

REVOKE ALL ON FUNCTION engano_snapshot(TEXT) FROM PUBLIC, anon, authenticated;

COMMIT;
